export function filterMockProperties(filters = {}) {
  let result = [...MOCK_PROPERTIES];

  if (filters.city) {
    result = result.filter(p => p.city.toLowerCase().includes(filters.city.toLowerCase()));
  }

  if (filters.property_type && filters.property_type !== 'All') {
    result = result.filter(p => p.property_type.toLowerCase() === filters.property_type.toLowerCase());
  }

  if (filters.listing_type && filters.listing_type !== 'All') {
    result = result.filter(p => p.listing_type.toLowerCase() === filters.listing_type.toLowerCase());
  }

  if (filters.minPrice) {
    result = result.filter(p => p.price >= Number(filters.minPrice));
  }

  if (filters.maxPrice) {
    result = result.filter(p => p.price <= Number(filters.maxPrice));
  }

  if (filters.bedrooms && filters.bedrooms !== 'Any') {
    result = result.filter(p => p.bedrooms >= Number(filters.bedrooms));
  }

  if (filters.bathrooms && filters.bathrooms !== 'Any') {
    result = result.filter(p => p.bathrooms >= Number(filters.bathrooms));
  }

  if (filters.furnishing && filters.furnishing !== 'Any') {
    result = result.filter(p => p.furnishing.toLowerCase() === filters.furnishing.toLowerCase());
  }

  if (filters.parking) {
    result = result.filter(p => p.parking_spaces > 0);
  }

  if (filters.owner_id) {
    result = result.filter(p => p.owner_id === Number(filters.owner_id));
  }

  const sort = filters.sort || 'newest';
  if (sort === 'price_low') result.sort((a, b) => a.price - b.price);
  else if (sort === 'price_high') result.sort((a, b) => b.price - a.price);
  else if (sort === 'area_largest') result.sort((a, b) => b.area_sqft - a.area_sqft);
  else if (sort === 'most_popular') result.sort((a, b) => b.view_count - a.view_count);
  else if (sort === 'oldest') result.sort((a, b) => new Date(a.created_at) - new Date(b.created_at));
  else result.sort((a, b) => new Date(b.created_at) - new Date(a.created_at));

  const page = Number(filters.page || 1);
  const limit = Number(filters.limit || 12);
  const total = result.length;
  const totalPages = Math.ceil(total / limit);
  const startIndex = (page - 1) * limit;
  const paginated = result.slice(startIndex, startIndex + limit);

  return {
    properties: paginated,
    total,
    page,
    totalPages
  };
}

